#!/usr/bin/env node
// Captures the website's clickable demo (website/demo/): every tour screen of the demo household, in Hebrew and
// English, plus where each sidebar link sits on it, so the tour's hotspots line up with the real app.
// 1. npm run demo            (made-up household on http://127.0.0.1:3000, or PENNY_DEMO_PORT)
// 2. node scripts/capture-demo-tour.mjs [base-url]
// Never point it at your own data: it screenshots whatever the server shows.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASE = process.argv[2] ?? `http://127.0.0.1:${process.env.PENNY_DEMO_PORT ?? 3000}`;
const OUT = path.join(ROOT, "website", "demo");
const VIEW = { width: 1440, height: 900 };

/** Tour screens, in order; `id` names the image and the step. */
export const SCREENS = [
  ["home", "/"],
  ["savings", "/optimizations"],
  ["budget", "/budget"],
  ["transactions", "/transactions"],
  ["accounts", "/accounts"],
  ["loans", "/loans"],
  ["investments", "/investments"],
  ["groups", "/groups"],
  ["overview", "/overview"],
  ["fi", "/fi"],
  ["insurance", "/insurance"],
];

const health = await fetch(`${BASE}/api/health`).catch(() => null);
if (!health?.ok) {
  console.error(`No app at ${BASE}. Start the demo first: npm run demo`);
  process.exit(1);
}

const browser = await chromium.launch({ channel: process.env.CI ? undefined : "chrome" });
const hotspots = {};
for (const lang of ["he", "en"]) {
  const context = await browser.newContext({ viewport: VIEW, colorScheme: "light", locale: lang === "he" ? "he-IL" : "en-US", reducedMotion: "reduce" });
  await context.addCookies([{ name: "NEXT_LOCALE", value: lang, url: BASE }]);
  const page = await context.newPage();
  // Two profiles: pick the first one, as a person would.
  await page.goto(`${BASE}/profiles`);
  await page.getByRole("button", { name: lang === "he" ? "דנה" : /Dana|דנה/ }).first().click();
  await page.waitForURL((u) => !u.pathname.startsWith("/profiles"));
  fs.mkdirSync(path.join(OUT, lang), { recursive: true });
  hotspots[lang] = {};
  for (const [id, url] of SCREENS) {
    await page.goto(`${BASE}${url}`);
    await page.waitForLoadState("networkidle");
    await page.waitForTimeout(1200); // charts settle
    await page.evaluate(() => window.scrollTo(0, 0));
    const png = await page.screenshot();
    await sharp(png).webp({ quality: 82 }).toFile(path.join(OUT, lang, `${id}.webp`));
    // Where each tour screen's link is visible on this screen, as percentages of the viewport.
    hotspots[lang][id] = await page.evaluate(({ screens, view }) => {
      const out = [];
      for (const [target, href] of screens) {
        for (const a of document.querySelectorAll(`a[href="${href}"]`)) {
          const r = a.getBoundingClientRect();
          const style = getComputedStyle(a);
          if (r.width < 8 || r.height < 8 || r.bottom <= 0 || r.top >= view.height || style.visibility === "hidden") continue;
          out.push({ to: target, x: +(r.left / view.width * 100).toFixed(2), y: +(r.top / view.height * 100).toFixed(2), w: +(r.width / view.width * 100).toFixed(2), h: +(r.height / view.height * 100).toFixed(2) });
          break;
        }
      }
      return out;
    }, { screens: SCREENS, view: VIEW });
    console.log(`${lang} ${id}: ${hotspots[lang][id].length} links`);
  }
  await context.close();
}
await browser.close();
fs.writeFileSync(path.join(OUT, "hotspots.js"), `// Generated by scripts/capture-demo-tour.mjs. Do not edit.\nwindow.PENNY_TOUR_HOTSPOTS = ${JSON.stringify(hotspots)};\n`);
console.log(`Done: ${OUT}`);
