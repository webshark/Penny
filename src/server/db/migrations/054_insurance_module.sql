-- Insurance moves from a name-and-premium list to a real module: the policy's
-- documents, its paying account, the text that identifies it on the statement,
-- cover and deductible, the agent, and an archive flag for policies that ended.
-- monthly_premium stays the monthly cost (the only number the budget and the
-- net-worth view use), so older code keeps working.
ALTER TABLE insurance_policies ADD COLUMN policy_number TEXT;
ALTER TABLE insurance_policies ADD COLUMN payment_account TEXT;
ALTER TABLE insurance_policies ADD COLUMN match_pattern TEXT;
ALTER TABLE insurance_policies ADD COLUMN start_date TEXT;
ALTER TABLE insurance_policies ADD COLUMN end_date TEXT;
ALTER TABLE insurance_policies ADD COLUMN coverage REAL;
ALTER TABLE insurance_policies ADD COLUMN deductible REAL;
ALTER TABLE insurance_policies ADD COLUMN agent_name TEXT;
ALTER TABLE insurance_policies ADD COLUMN agent_phone TEXT;
ALTER TABLE insurance_policies ADD COLUMN notes TEXT;
ALTER TABLE insurance_policies ADD COLUMN archived INTEGER NOT NULL DEFAULT 0;
ALTER TABLE insurance_policies ADD COLUMN updated_at TEXT;

CREATE INDEX idx_policies_archived ON insurance_policies(workspace_id, archived);

-- A policy's documents live on disk under data/policies/<workspace>/<policy>/.
-- file_name is generated by us, never the user's name.
CREATE TABLE insurance_documents (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  policy_id INTEGER NOT NULL REFERENCES insurance_policies(id) ON DELETE CASCADE,
  file_name TEXT NOT NULL,
  original_name TEXT NOT NULL,
  mime TEXT NOT NULL,
  size INTEGER NOT NULL,
  kind TEXT NOT NULL DEFAULT 'policy' CHECK(kind IN ('policy','appendix','renewal','claim','other')),
  uploaded_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX idx_insurance_documents_policy ON insurance_documents(policy_id);
CREATE INDEX idx_insurance_documents_workspace ON insurance_documents(workspace_id);
